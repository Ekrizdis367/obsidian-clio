/**
 * Build the effective word list from settings: built-in plus custom, with
 * dedupe. When `replaceBuiltIn` is set the custom list is the entire
 * source (assuming it has any entries).
 */
export function buildWordList(
	customRaw: string,
	replaceBuiltIn: boolean,
): readonly string[] {
	const custom = customRaw
		.split(/\r?\n/)
		.map((s) => s.trim().toLowerCase())
		.filter((s) => s.length > 0 && /^[a-z][a-z'-]*$/i.test(s));
	if (replaceBuiltIn && custom.length > 0) {
		return Array.from(new Set(custom));
	}
	if (custom.length === 0) return ADVANCED_WORDS;
	return Array.from(new Set([...ADVANCED_WORDS, ...custom]));
}
